apiRouter.use('/saved-billers', requireAuth, savedBillerRoutes);
apiRouter.use('/requests', requireAuth, requestRoutes);
apiRouter.use('/pockets', requireAuth, pocketRoutes);
apiRouter.use('/cards', requireAuth, cardRoutes);
apiRouter.use('/statements', requireAuth, statementRoutes);
apiRouter.use('/qr', requireAuth, qrRoutes);
apiRouter.use('/chat', requireAuth, chatRoutes);
apiRouter.get('/billers', requireAuth, handler(listBillers));
apiRouter.get('/telcos', requireAuth, handler(listTelcos));
apiRouter.post('/recharges', requireAuth, handler(createRecharge));
