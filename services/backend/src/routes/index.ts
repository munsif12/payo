import { Router } from 'express';
import { handler } from '../lib/handler';
import { requireAuth } from '../middleware/requireAuth';
import { authRoutes } from './authRoutes';
import { actionRoutes } from './actionRoutes';
import { institutionRoutes } from './institutionRoutes';
import { recipientRoutes } from './recipientRoutes';
import { transferRoutes } from './transferRoutes';
import { transactionRoutes } from './transactionRoutes';
import { billRoutes } from './billRoutes';
import { savedBillerRoutes } from './savedBillerRoutes';
import { requestRoutes } from './requestRoutes';
import { pocketRoutes } from './pocketRoutes';
import { cardRoutes } from './cardRoutes';
import { statementRoutes } from './statementRoutes';
import { qrRoutes } from './qrRoutes';
import { chatRoutes } from './chatRoutes';
import { listBillers } from '../controllers/billsController';
import { listTelcos, createRecharge } from '../controllers/rechargesController';
import { me } from '../controllers/authController';
import { updateMe } from '../controllers/meController';
